import { afterAll, beforeAll, describe, expect, test } from 'vitest'
import { config, requireAnonKey, requireServiceRoleKey } from '../src/env.js'
import { apiRequest, expectOk, expectStatus, pgQuery } from '../src/http.js'

describe('rest', () => {
  const table = `codex_rest_probe_${config.runId.replaceAll('-', '_')}`

  beforeAll(async () => {
    const service = requireServiceRoleKey()
    const query = [
      `create table public.${table} (id bigint generated by default as identity primary key, name text not null)`,
      `alter table public.${table} enable row level security`,
      `create policy ${table}_service_all on public.${table} for all to service_role using (true) with check (true)`,
      `grant all on public.${table} to service_role`,
      `grant usage on sequence public.${table}_id_seq to service_role`,
      `notify pgrst, 'reload schema'`,
    ].join('; ')
    expectOk(await pgQuery(query, service), 'rest create probe table')
  })

  afterAll(async () => {
    const service = requireServiceRoleKey()
    await pgQuery(`drop table if exists public.${table};`, service)
  })

  test('OpenAPI requires an admin key', async () => {
    const anon = requireAnonKey()
    expectStatus(await apiRequest('/rest/v1/', { key: anon }), [403], 'rest openapi anon')

    if (config.publishableKey) {
      expectStatus(await apiRequest('/rest/v1/', { key: config.publishableKey }), [403], 'rest openapi publishable')
    }
    expectOk(await apiRequest('/rest/v1/', { key: requireServiceRoleKey() }), 'rest openapi service')
  })

  test('service role can insert and select via PostgREST', async () => {
    const service = requireServiceRoleKey()
    await expect.poll(async () => (await apiRequest(`/rest/v1/${table}?select=id`, { key: service })).response.status).toBe(200)
    expectOk(
      await apiRequest(`/rest/v1/${table}`, {
        method: 'POST',
        key: service,
        headers: { Prefer: 'return=representation' },
        json: { name: 'ok' },
      }),
      'rest insert service',
    )

    expectOk(
      await apiRequest(`/rest/v1/${table}?select=id,name`, {
        key: service,
      }),
      'rest select service',
    )
  })
})
